export function resolveGunPresetForCategory(towerId: string, category: string, vfxPreset?: string): GunVfxPresetId {
  if (vfxPreset && vfxPreset in GUN_VFX_PRESETS) return vfxPreset as GunVfxPresetId;
  if (towerId === 'turret') return 'autocannon';
  if (category === 'sniper') return 'sniper';
  if (category === 'explosive') return 'heavy_cannon';
  return 'rifle';
}
